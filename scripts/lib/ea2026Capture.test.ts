import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { CaptureQueue, sha256 } from './ea2026Capture.js';
import { verifyEaExtraction, verifyEaSourceCaptures } from './ea2026SourceEvidence.js';
const directory = mkdtempSync(join(tmpdir(), 'ea-capture-test-'));
let now = 100000000, calls = 0;
let respond = () => new Response('official content', { status: 200, headers: { etag: 'v1' } });
const transport = (async () => { calls++; return respond(); }) as typeof fetch;
const queue = new CaptureQueue(directory, join(directory, 'requests.jsonl'), transport, () => now);
queue.add([{ state: 'CA', url: 'https://example.gov/list#one', purpose: 'ballot' }, { state: 'US', url: 'https://example.gov/list#two', purpose: 'review' }, { state: 'CA', url: 'https://example.gov/other', purpose: 'ballot' }]);
assert.equal(Object.keys(queue.state.entries).length, 2);
assert.equal((await queue.run(() => true, 25)).completed, 1);
assert.equal(calls, 1);
const extracted = queue.extract('https://example.gov/list', 'official content', 'fixture/plain-text-v1');
assert.equal(extracted.sourceDigest, sha256('official content'));
verifyEaExtraction(directory, extracted);
queue.recordReview('https://example.gov/list', extracted.sourceDigest, { reviewer: 'test', locator: 'fixture body', reviewedAt: new Date(now).toISOString() }, sha256('input'));
assert.equal(Object.values(queue.state.entries)[0].imported, true);
assert.throws(() => queue.recordReview('https://example.gov/other', '0'.repeat(64), { reviewer: 'test', locator: 'none', reviewedAt: new Date(now).toISOString() }), /matching extracted/);
const source = Object.values(queue.state.entries)[0].receipt!;
verifyEaSourceCaptures([{ ...source } as any], directory);
writeFileSync(join(directory, 'bodies', extracted.file), 'tampered text');
assert.throws(() => verifyEaExtraction(directory, extracted), /integrity/);
assert.throws(() => queue.recordReview('https://example.gov/list', extracted.sourceDigest, { reviewer: 'test', locator: 'fixture', reviewedAt: new Date(now).toISOString() }), /extraction integrity/, 'review fails closed on corrupted extracted text');
const restart = new CaptureQueue(directory, join(directory, 'requests.jsonl'), transport, () => now);
assert.equal((await restart.run(() => true, 25)).completed, 0);
now += 3001;
respond = () => new Response('', { status: 429, headers: { 'retry-after': '1200' } });
await restart.run(() => true, 25);
const other = restart.state.entries[sha256('https://example.gov/other')];
assert.ok(other.nextEligible >= now + 1200000);
now += 1200001;
respond = () => new Response('', { status: 403 });
await restart.run(() => true, 25);
assert.equal(other.status, 'blocked');
now += 3001;
await restart.run(() => true, 25); assert.equal(calls, 3);
restart.refresh(other.url);
respond = () => new Response('replacement', { status: 200 });
await restart.run(() => true, 25); assert.equal(other.status, 'succeeded');
const legacy = join(directory, 'legacy'); mkdirSync(legacy);
writeFileSync(join(legacy, 'body.html'), 'legacy');
writeFileSync(join(legacy, 'capture-receipt.json'), JSON.stringify({ captures: [{ url: 'https://other.gov/list', status: 'captured_unreviewed', bodyFile: 'body.html', sha256: sha256('legacy') }] }));
restart.add([{ state: 'CA', url: 'https://other.gov/list', purpose: 'ballot' }]);
assert.equal(restart.reuse(legacy), 1);
const cached = restart.state.entries[sha256('https://other.gov/list')].receipt!;
writeFileSync(join(directory, 'bodies', cached.bodyFile), 'tampered');
assert.throws(() => restart.body(cached), /integrity/);
assert.ok(readFileSync(join(directory, 'requests.jsonl'), 'utf8').includes('http_429'));
const retryDir = mkdtempSync(join(tmpdir(), 'ea-retry-test-'));
let retries = 0;
const throttled = new CaptureQueue(retryDir, join(retryDir, 'requests.jsonl'), (async () => { retries++; return new Response('', { status: 429 }); }) as typeof fetch, () => now);
throttled.add([{ state: 'CA', url: 'https://rate.gov/a', purpose: 'ballot' }]);
for (let i = 0; i < 4; i++) { await throttled.run(() => true, 1); now += 601001; }
await throttled.run(() => true, 1);
assert.equal(retries, 4, 'at most initial plus three retries per rolling day');
assert.ok(throttled.state.hosts['rate.gov'].rateLimits >= 3);
assert.equal(Object.values(throttled.state.entries)[0].status, 'deferred');
const conditionalDir = mkdtempSync(join(tmpdir(), 'ea-conditional-test-'));
let conditionalCalls = 0;
const conditional = new CaptureQueue(conditionalDir, join(conditionalDir, 'requests.jsonl'), (async (_url, options) => {
  conditionalCalls++;
  if (conditionalCalls === 1) return new Response('unchanged', { headers: { etag: 'test-etag' } });
  assert.equal((options?.headers as Record<string, string>)['if-none-match'], 'test-etag');
  return new Response(null, { status: 304 });
}) as typeof fetch, () => now);
conditional.add([{ state: 'CA', url: 'https://conditional.gov/a', purpose: 'ballot' }]);
await conditional.run(() => true, 1); now += 3001; conditional.refresh('https://conditional.gov/a');
await conditional.run(() => true, 1);
assert.equal(Object.values(conditional.state.entries)[0].status, 'succeeded');
console.log('PASS: deduplication, persisted pacing, cache reuse, extraction binding, Retry-After, blocked failures, explicit refresh, tamper detection');
